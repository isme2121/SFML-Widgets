#pragma once
#include "widgets.hpp"
#if defined(WIDGETS_HPP) && defined(BUILD_EDITOR_GUI)
#define WRAPPER_DEFINED

namespace sfml_widgets
{
///////////////////////////////////////////////////////////////////
/// @brief Base wrapper class for ImGui
///
///////////////////////////////////////////////////////////////////
class ImGuiFrame : public external_widget
{
public:
    ///////////////////////////////////////////////////////////////////
    /// @brief Constructs ImGui frame on window
    ///
    ///////////////////////////////////////////////////////////////////
    explicit ImGuiFrame(sf::RenderWindow&, const std::string& = "");

    ImGuiFrame(const ImGuiFrame&) = delete;
    ImGuiFrame& operator=(const ImGuiFrame&) = delete;
    ImGuiFrame(ImGuiFrame&&) = delete;
    ImGuiFrame& operator=(ImGuiFrame&&) = delete;

    virtual ~ImGuiFrame();

    ///////////////////////////////////////////////////////////////////
    /// @brief Updates and draws the frame to the window
    ///
    ///////////////////////////////////////////////////////////////////
    void draw() override;

    ///////////////////////////////////////////////////////////////////
    /// @brief Captures all events
    ///
    ///////////////////////////////////////////////////////////////////
    bool captureEvents(const sf::Event&) override;

    ///////////////////////////////////////////////////////////////////
    /// @brief Updates the ImGui frame title
    ///
    ///////////////////////////////////////////////////////////////////
    void setTitle(const std::string&);

    ///////////////////////////////////////////////////////////////////
    /// @brief Turns the frame visible
    ///
    ///////////////////////////////////////////////////////////////////
    void show();

    ///////////////////////////////////////////////////////////////////
    /// @brief Turns the frame invisible
    ///
    ///////////////////////////////////////////////////////////////////
    void hide();

    ///////////////////////////////////////////////////////////////////
    /// @brief Toggles the current visibility state
    ///
    ///////////////////////////////////////////////////////////////////
    void toggle();

    ///////////////////////////////////////////////////////////////////
    /// @brief Returns whether the frame is hidden or not
    ///
    ///////////////////////////////////////////////////////////////////
    bool isHidden() const;

protected:
    ///////////////////////////////////////////////////////////////////
    /// @brief Called within `captureEvents` for any additional event handling
    /// from derived class
    ///
    ///////////////////////////////////////////////////////////////////
    virtual bool processEvents(const sf::Event&) = 0;

    ///////////////////////////////////////////////////////////////////
    /// @brief Called within `render` for any derived class widgets
    ///
    ///////////////////////////////////////////////////////////////////
    virtual void renderWidgets() = 0;

    ///////////////////////////////////////////////////////////////////
    /// @brief Renders any non ImGui content
    ///
    ///////////////////////////////////////////////////////////////////
    virtual void renderWinElements() = 0;

    sf::RenderWindow& m_window;     //!< root window
private:
    sf::Clock m_deltaClock;         //!< internal update clock
    std::string m_title;            //!< frame title
    unsigned int m_ID{0};           //!< unique frame ID
    bool m_guiVisible{true};        //!< visiblity indicator
    bool m_hovered{false};          //!< hovered flag updated on each loop
    bool m_keyboardEventUsed{false};

    inline static unsigned int s_instanceCount{0};  //!< maintain separation between multiple ImGui frames
};
}
#endif